CREATE TABLE IF NOT EXISTS facility (
 id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL, location VARCHAR(120) NOT NULL,
 capacity INTEGER NOT NULL CHECK(capacity>0), enabled BOOLEAN NOT NULL
);
CREATE TABLE IF NOT EXISTS reservation (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 facility_id BIGINT NOT NULL REFERENCES facility(id), applicant VARCHAR(40) NOT NULL,
 use_date VARCHAR(10) NOT NULL, start_time VARCHAR(5) NOT NULL, end_time VARCHAR(5) NOT NULL,
 people INTEGER NOT NULL CHECK(people>0), purpose VARCHAR(300) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK(status IN ('REQUESTED','APPROVED','REJECTED','CANCELLED')),
 reason VARCHAR(300) NOT NULL, CHECK(start_time<end_time)
);
CREATE INDEX IF NOT EXISTS ix_reservation_schedule ON reservation(facility_id,use_date,status);
CREATE TABLE IF NOT EXISTS reservation_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 reservation_id BIGINT NOT NULL REFERENCES reservation(id), actor VARCHAR(40) NOT NULL,
 previous_status VARCHAR(20) NOT NULL, status VARCHAR(20) NOT NULL,
 reason VARCHAR(300) NOT NULL, occurred_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE facility IS '대관 시설';
COMMENT ON TABLE reservation IS '시설 사용 신청';
COMMENT ON TABLE reservation_event IS '신청 처리 이력';
