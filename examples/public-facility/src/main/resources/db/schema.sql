CREATE TABLE facility (
 id BIGINT PRIMARY KEY, name VARCHAR(80) NOT NULL, location VARCHAR(120) NOT NULL,
 capacity INTEGER NOT NULL CHECK (capacity > 0), active BOOLEAN NOT NULL
);
CREATE TABLE booking (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 facility_id BIGINT NOT NULL REFERENCES facility(id), applicant VARCHAR(40) NOT NULL,
 use_date DATE NOT NULL, start_time VARCHAR(5) NOT NULL, end_time VARCHAR(5) NOT NULL,
 attendees INTEGER NOT NULL CHECK (attendees > 0), purpose VARCHAR(300) NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('REQUESTED','APPROVED','REJECTED','CANCELLED')),
 reason VARCHAR(300) NOT NULL DEFAULT '', CHECK (start_time < end_time)
);
CREATE INDEX ix_booking_slot ON booking(facility_id,use_date,status);
CREATE TABLE booking_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 booking_id BIGINT NOT NULL REFERENCES booking(id), actor VARCHAR(40) NOT NULL,
 from_status VARCHAR(20) NOT NULL, to_status VARCHAR(20) NOT NULL,
 reason VARCHAR(300) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
COMMENT ON TABLE facility IS '대관 시설';
COMMENT ON TABLE booking IS '시설 사용 신청';
COMMENT ON TABLE booking_history IS '신청 상태 변경 이력';
