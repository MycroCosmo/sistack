CREATE TABLE COMMON_CODE (
    CODE VARCHAR2(20) PRIMARY KEY,
    LABEL VARCHAR2(100) NOT NULL
);

CREATE TABLE APP_MENU (
    ROLE_KEY VARCHAR2(20) NOT NULL,
    MENU_ORDER NUMBER(5) NOT NULL,
    LABEL VARCHAR2(100) NOT NULL,
    URL VARCHAR2(200) NOT NULL
);

CREATE SEQUENCE BOARD_SEQ START WITH 1 INCREMENT BY 1;

CREATE TABLE BOARD (
    ID NUMBER(19) PRIMARY KEY,
    TITLE VARCHAR2(200) NOT NULL,
    CONTENT VARCHAR2(4000) NOT NULL,
    AUTHOR VARCHAR2(100) NOT NULL,
    CATEGORY VARCHAR2(20) NOT NULL REFERENCES COMMON_CODE(CODE),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

COMMENT ON TABLE COMMON_CODE IS '게시판 분류 공통코드';
COMMENT ON COLUMN COMMON_CODE.CODE IS '분류 코드';
COMMENT ON COLUMN COMMON_CODE.LABEL IS '분류명';

COMMENT ON TABLE APP_MENU IS '권한별 메뉴';
COMMENT ON COLUMN APP_MENU.ROLE_KEY IS '권한 코드';
COMMENT ON COLUMN APP_MENU.MENU_ORDER IS '메뉴 순서';
COMMENT ON COLUMN APP_MENU.LABEL IS '메뉴명';
COMMENT ON COLUMN APP_MENU.URL IS '메뉴 주소';

COMMENT ON TABLE BOARD IS '게시판';
COMMENT ON COLUMN BOARD.ID IS '게시글 번호';
COMMENT ON COLUMN BOARD.TITLE IS '제목';
COMMENT ON COLUMN BOARD.CONTENT IS '내용';
COMMENT ON COLUMN BOARD.AUTHOR IS '작성자명';
COMMENT ON COLUMN BOARD.CATEGORY IS '게시판 분류 코드';
COMMENT ON COLUMN BOARD.CREATED_AT IS '등록 일시';
