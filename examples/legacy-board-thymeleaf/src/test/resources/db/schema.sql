CREATE TABLE COMMON_CODE (CODE VARCHAR2(20) PRIMARY KEY, LABEL VARCHAR2(100) NOT NULL);
CREATE TABLE APP_MENU (ROLE_KEY VARCHAR2(20) NOT NULL, MENU_ORDER NUMBER(5) NOT NULL, LABEL VARCHAR2(100) NOT NULL, URL VARCHAR2(200) NOT NULL);
CREATE SEQUENCE BOARD_SEQ START WITH 1 INCREMENT BY 1;
CREATE TABLE BOARD (
  ID NUMBER(19) PRIMARY KEY,
  TITLE VARCHAR2(200) NOT NULL,
  CONTENT VARCHAR2(4000) NOT NULL,
  AUTHOR VARCHAR2(100) NOT NULL,
  CATEGORY VARCHAR2(20) NOT NULL REFERENCES COMMON_CODE(CODE),
  CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);
